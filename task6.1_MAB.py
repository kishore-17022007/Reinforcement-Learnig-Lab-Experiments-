import pandas as pd


dataset = pd.read_csv('/content/Ads_CTR_Optimisation.csv')


print("Dataset shape:", dataset.shape)
display(dataset.head())

import random


N = dataset.shape[0]


d = dataset.shape[1]

ads_selected = []


numbers_of_selections = [0] * d


sums_of_rewards = [0] * d

total_reward = 0

epsilon = 0.1

print(f"Number of users (N): {N}")
print(f"Number of ads (d): {d}")
print(f"Epsilon value: {epsilon}")

for n in range(N):
    ad = 0
    if random.random() < epsilon: # Exploration
        ad = random.randrange(d)
    else: # Exploitation
        max_upper_bound = 0
        for i in range(d):
            if numbers_of_selections[i] > 0:
                average_reward = sums_of_rewards[i] / numbers_of_selections[i]
            else:

                average_reward = 0


            if average_reward > max_upper_bound:
                max_upper_bound = average_reward
                ad = i

    ads_selected.append(ad)
    numbers_of_selections[ad] += 1
    reward = dataset.values[n, ad]
    sums_of_rewards[ad] += reward
    total_reward += reward

print(f"Total reward: {total_reward}")
print(f"Ad selections count: {numbers_of_selections}")

import matplotlib.pyplot as plt
average_rewards = [sums_of_rewards[i] / numbers_of_selections[i] if numbers_of_selections[i] > 0 else 0 for i in range(d)]

best_ad_index = average_rewards.index(max(average_rewards))
print(f"The best ad is Ad {best_ad_index + 1} with an average reward of {max(average_rewards):.4f}.")

# Visualize the histogram of ad selections
fig = plt.figure(figsize=(10, 6))
plt.hist(ads_selected, bins=range(d + 1), rwidth=0.8, align='left')
plt.title('Histogram of Ad Selections (Epsilon-Greedy)')
plt.xlabel('Ad Number')
plt.ylabel('Number of Times Each Ad Was Selected')
plt.xticks(range(d), [f'Ad {i+1}' for i in range(d)])
plt.show()